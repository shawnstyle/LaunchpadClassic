import Foundation

var checks = 0
func check(_ condition: @autoclosure () -> Bool, _ message: String) {
    checks += 1
    if !condition() { fatalError("失败：\(message)") }
}
let wechat = AppRecord(path: "/Applications/WeChat.app", name: "微信", bundleID: "com.tencent.xinWeChat")
check(wechat.matches("微信"), "中文名称")
check(wechat.matches("weixin"), "完整拼音")
check(wechat.matches("wx"), "拼音首字母")
check(wechat.matches("wechat"), "英文文件名")
check(wechat.matches("WECHAT"), "忽略大小写")
check(!wechat.matches("not-an-app"), "不匹配查询")
check(wechat.matches(" wei xin "), "多词查询")
let multilingual = AppRecord(path: "/Applications/WeChat.app", name: "WeChat", aliases: ["微信"])
check(multilingual.matches("微信") && multilingual.matches("weixin") && multilingual.matches("wx"), "英文系统下中文别名搜索")
let terminal = AppRecord(path: "/System/Applications/Utilities/Terminal.app", name: "终端")
check(terminal.matches("zhongduan"), "拼音去声调")
check(terminal.matches("zd"), "中文首字母")
let grid = GridGeometry(width: 1512, height: 982)
check(grid.columns == 7 && grid.rows == 5 && grid.capacity == 35, "经典七列五行")
check(grid.firstIconCenterY < grid.height * 0.20 && grid.pageCenterY > grid.height * 0.85, "首行和页码位置")
check(grid.searchWidth == 250 && grid.searchHeight == 26 && grid.iconSize == 96, "1512×982 参考尺寸")
let retinaEquivalent = GridGeometry(width: 1728, height: 1117)
check(retinaEquivalent.columns == 7 && retinaEquivalent.capacity == 35, "屏幕缩放不改变分页容量")
check(grid.pageCount(for: 0) == 1, "空列表页数")
check(grid.pageCount(for: grid.capacity) == 1, "整页边界")
check(grid.pageCount(for: grid.capacity + 1) == 2, "跨页边界")
check(GridGeometry(width: 600, height: 400).capacity >= 8, "小屏幕布局")
var layout = LaunchLayout()
layout.reconcile(with: ["a", "b", "c"])
check(layout.entries.count == 3, "初次扫描")
layout.group("a", with: "b")
check(layout.entries.count == 2 && layout.entries[0].isFolder, "拖拽创建文件夹")
let folderID = layout.entries[0].id
check(layout.entries[0].appIDs == ["b", "a"], "文件夹包含两个应用")
layout.place("c", in: folderID)
check(layout.entries.count == 1 && layout.entries[0].appIDs.count == 3, "移入文件夹")
layout.place("a", in: folderID)
check(layout.entries[0].appIDs.count == 3, "重复移入不丢应用")
layout.ungroup("a")
check(layout.entries.count == 2 && layout.entries.last?.id == "a", "移出文件夹")
layout.reconcile(with: ["a", "b", "c", "d"])
check(layout.entries.count == 3, "新安装应用自动加入")
check(layout.entries[0].appIDs == ["b", "c"], "刷新保留文件夹")
layout.reconcile(with: ["a"])
check(layout.entries.count == 3, "暂时缺失应用保留排列")
let data = try JSONEncoder().encode(layout)
let decoded = try JSONDecoder().decode(LaunchLayout.self, from: data)
check(decoded == layout, "排列持久化")
layout.move("d", before: folderID)
check(layout.entries.first?.id == "d", "调整顺序")
let allIDs = layout.entries.flatMap(\.appIDs)
check(Set(allIDs).count == allIDs.count, "所有操作后没有重复应用")
print("通过 \(checks) 项核心检查")
