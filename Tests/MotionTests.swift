import Foundation
import AppKit
import CoreGraphics

@main
struct MotionTests {
    @MainActor static func main() async throws {
        var checks = 0
        func check(_ condition: @autoclosure () -> Bool, _ message: String) {
            checks += 1
            precondition(condition(), message)
        }
        let width = 1000.0
        check(PageSwipePhysics.destination(offset: -100, velocity: 0, page: 1, count: 3, width: width) == 1, "短距离滑动回弹")
        check(PageSwipePhysics.destination(offset: -250, velocity: 0, page: 1, count: 3, width: width) == 2, "向左滑动进入下一页")
        check(PageSwipePhysics.destination(offset: 250, velocity: 0, page: 1, count: 3, width: width) == 0, "向右滑动进入上一页")
        check(PageSwipePhysics.destination(offset: -20, velocity: -1900, page: 1, count: 3, width: width) == 2, "短距离快速甩动使用速度预测")
        check(PageSwipePhysics.destination(offset: -5, velocity: -2400, page: 1, count: 3, width: width) == 1, "轻微手抖不误翻页")
        check(PageSwipePhysics.destination(offset: -900, velocity: -1900, page: 1, count: 3, width: width, cancelled: true) == 1, "手势取消不提交页码")
        check(PageSwipePhysics.destination(offset: 900, velocity: 1900, page: 0, count: 3, width: width) == 0, "第一页不能越界")
        check(PageSwipePhysics.destination(offset: -900, velocity: -1900, page: 2, count: 3, width: width) == 2, "最后一页不能越界")
        let rubber = PageSwipePhysics.displacement(300, page: 0, count: 3, width: width)
        check(rubber > 0 && rubber < 100, "边界滑动有阻尼")
        check(PageSwipePhysics.displacement(-300, page: 1, count: 3, width: width) == -300, "正常页面一对一跟手")
        check(PageSwipePhysics.displacement(-5000, page: 1, count: 3, width: width) == -980, "单次手势位移有界")

        let suite = "org.launchpadclassic.tests.MotionTests.\(UUID().uuidString)"
        let prefs = UserDefaults(suiteName: suite)!
        defer { prefs.removePersistentDomain(forName: suite) }
        let model = LauncherModel(defaults: prefs, openApplication: { _, completion in completion(nil) })
        let apps = (0..<80).map { AppRecord(path: "/Applications/Test\($0).app", name: "Test \($0)") }
        model.apps = apps
        model.layout = LaunchLayout(entries: apps.map { .app($0.id) })
        model.save()
        let baseline = model.layout
        model.beginDrag(apps[0].id, source: NSObject())
        check(model.editing, "拖动过程中临时抖动")
        model.hover(.app(apps[3].id), center: false, inFolder: nil)
        try await Task.sleep(nanoseconds: 180_000_000)
        check(model.layout != baseline, "悬停侧边时先预览让位")
        model.save()
        let storedPreview = try JSONDecoder().decode(LaunchLayout.self, from: prefs.data(forKey: "layout")!)
        check(storedPreview == baseline, "拖动预览不污染持久化排列")
        model.finishDrag(operationSucceeded: false)
        check(model.layout == baseline && model.dragging == nil && model.activeDragSource == nil, "取消拖动恢复完整布局并释放拖拽源")
        check(model.hoverWork == nil && model.edgeWork == nil, "取消后清理悬停和跨页计时器")
        check(!model.editing, "取消拖动后退出临时抖动")
        model.enterEditing()
        model.beginDrag(apps[0].id, source: NSObject())
        _ = model.drop(on: .app(apps[0].id), inFolder: nil)
        model.finishDrag(operationSucceeded: true)
        check(model.editing, "长按进入的编辑模式在拖动释放后保留")
        var dismissCount = 0
        model.dismiss = { dismissCount += 1 }
        model.backgroundClicked()
        check(!model.editing && dismissCount == 0, "编辑模式点空白只退出编辑，不收起界面")
        model.backgroundClicked()
        check(dismissCount == 1, "普通模式点空白正常收起")

        model.beginDrag(apps[0].id, source: NSObject())
        model.hover(.app(apps[1].id), center: true, inFolder: nil)
        check(!model.folderDropReady, "经过中心不会立即误建文件夹")
        try await Task.sleep(nanoseconds: 560_000_000)
        check(model.folderDropReady && model.dropTargetID == apps[1].id, "停留后进入成组预览")
        check(model.drop(on: .app(apps[1].id), inFolder: nil), "成组目标接受落下")
        model.finishDrag(operationSucceeded: true)
        check(model.layout.entries.first?.isFolder == true, "悬停后落下创建文件夹")
        check(Set(model.layout.entries.flatMap(\.appIDs)) == Set(apps.map(\.id)), "成组后应用不丢失不重复")
        let committed = try JSONDecoder().decode(LaunchLayout.self, from: prefs.data(forKey: "layout")!)
        check(committed == model.layout, "落下成功才保存新排列")

        let grouped = model.layout
        let folder = model.layout.entries.first!
        check(!model.editing && model.folderID == folder.id, "新文件夹落位后自动展开且退出临时抖动")
        try await Task.sleep(nanoseconds: 370_000_000)
        check(model.folderRenameID == folder.id, "新文件夹展开后请求名称输入焦点")
        model.closeFolder()
        check(model.folderRenameID == nil && model.folderRenameWork == nil, "关闭文件夹清除命名请求")
        model.openFolder(folder.id, rename: true)
        model.closeFolder()
        try await Task.sleep(nanoseconds: 370_000_000)
        check(model.folderID == nil && model.folderRenameID == nil, "快速关闭不会被延时命名重新抢焦点")
        model.openFolder(folder.id); model.enterEditing(); model.backgroundClicked()
        check(!model.editing && model.folderID == folder.id, "文件夹内点空白先结束排列")
        model.closeFolder()
        model.beginDrag(apps[3].id, source: NSObject())
        model.hover(folder, center: true, inFolder: nil)
        try await Task.sleep(nanoseconds: 560_000_000)
        _ = model.drop(on: folder, inFolder: nil)
        model.finishDrag(operationSucceeded: true)
        try await Task.sleep(nanoseconds: 370_000_000)
        check(model.folderID == nil && model.folderRenameID == nil, "加入已有文件夹不会误触发新建命名")
        model.layout = grouped; model.save()
        model.beginDrag(apps[3].id, source: NSObject())
        model.hover(.app(apps[0].id), center: false, inFolder: folder.id)
        try await Task.sleep(nanoseconds: 180_000_000)
        check(model.layout.entries.first?.appIDs.contains(apps[3].id) == true, "拖进文件夹可预览内部让位")
        model.finishDrag(operationSucceeded: false)
        check(model.layout == grouped, "取消跨文件夹拖动恢复原分组")

        model.beginDrag(apps[3].id, source: NSObject())
        model.hover(folder, center: true, inFolder: nil)
        model.clearHover()
        try await Task.sleep(nanoseconds: 600_000_000)
        check(!model.folderDropReady && model.folderID == nil, "离开目标会撤销悬停激活")
        model.finishDrag(operationSucceeded: false)

        model.beginDrag(apps[3].id, source: NSObject())
        model.hover(folder, center: true, inFolder: nil)
        try await Task.sleep(nanoseconds: 1_020_000_000)
        check(model.folderID == folder.id, "停留在已有文件夹上会自动展开")
        model.finishDrag(operationSucceeded: false)
        check(model.folderID == nil && model.layout == grouped, "取消后恢复文件夹打开状态")

        model.layout = baseline; model.page = 0
        model.beginDrag(apps[0].id, source: NSObject())
        model.dragMoved(to: CGPoint(x: model.pageWidth - 1, y: 200))
        try await Task.sleep(nanoseconds: 720_000_000)
        check(model.page == 1, "拖动到边缘停留后自动翻页")
        model.finishDrag(operationSucceeded: false)
        check(model.page == 0 && model.layout == baseline, "取消跨页拖动恢复原页")
        try await Task.sleep(nanoseconds: 720_000_000)
        check(model.page == 0, "取消后遗留计时器不会继续翻页")
        model.layout = baseline; model.page = 0; model.folderID = nil; model.save()
        model.itemFrames = [apps[0].id: CGRect(x: 100, y: 100, width: 160, height: 120),
                            apps[1].id: CGRect(x: 300, y: 100, width: 160, height: 120)]
        model.beginDrag(apps[1].id, source: NSObject())
        model.endInternalDrag(at: CGPoint(x: 110, y: 130))
        check(!model.editing && model.dragSettling, "松手即停止临时抖动，落位动画继续完成")
        try await Task.sleep(nanoseconds: 350_000_000)
        check(model.dragging == nil && !model.dragSettling, "快速拖动释放后完整结束会话")
        check(model.layout.entries.first?.id == apps[1].id, "快速释放能提交实际落点")
        model.layout = baseline; model.save()
        model.beginDrag(apps[1].id, source: NSObject())
        model.endInternalDrag(at: CGPoint(x: -20, y: 130))
        try await Task.sleep(nanoseconds: 300_000_000)
        check(model.layout == baseline && model.dragging == nil, "拖出窗口释放会归位并清理")
        model.beginDrag(apps[1].id, source: NSObject())
        model.endInternalDrag(at: CGPoint(x: 110, y: 130))
        model.finishDrag(operationSucceeded: false)
        try await Task.sleep(nanoseconds: 350_000_000)
        check(model.layout == baseline && model.dragging == nil, "收起窗口会取消未结束的落位动画而不延迟提交")
        model.layout = baseline; model.page = 0
        model.beginDrag(apps[0].id, source: NSObject())
        model.hover(.app(apps[1].id), center: true, inFolder: nil)
        try await Task.sleep(nanoseconds: 560_000_000)
        _ = model.drop(on: .app(apps[1].id), inFolder: nil)
        model.finishDrag(operationSucceeded: false)
        try await Task.sleep(nanoseconds: 370_000_000)
        check(model.layout == baseline && model.folderID == nil && model.folderRenameID == nil, "新建文件夹的拖动被取消时不会展开或命名")
        model.enterEditing()
        model.beginDrag(apps[0].id, source: NSObject())
        model.finishDrag(operationSucceeded: false)
        check(model.editing, "取消拖动同样保留长按编辑模式")
        model.stopEditing()
        func wheel(_ delta: Int32, phase: CGScrollPhase) -> NSEvent {
            let cg = CGEvent(scrollWheelEvent2Source: nil, units: .pixel, wheelCount: 2, wheel1: 0, wheel2: delta, wheel3: 0)!
            cg.setIntegerValueField(.scrollWheelEventScrollPhase, value: Int64(phase.rawValue))
            return NSEvent(cgEvent: cg)!
        }
        let began = wheel(-180, phase: .began)
        model.scroll(began)
        check(model.swipeInProgress, "系统滚动事件开始手势跟踪")
        model.scroll(wheel(-180, phase: .changed))
        check(model.rawSwipe < 0, "系统滚动位移被正确接入")
        model.scroll(wheel(0, phase: .ended))
        check(model.page == 1 && !model.swipeInProgress && model.swipeOffset == 0, "收到抬手阶段后吸附到下一页")
        model.scroll(wheel(200, phase: .began))
        model.scroll(wheel(0, phase: .cancelled))
        check(model.page == 1 && !model.swipeInProgress, "系统取消阶段会回弹而不是翻页")
        model.swipeInProgress = true; model.swipeOffset = -100; model.rawSwipe = -100
        model.navigate(to: 0)
        check(!model.swipeInProgress && model.swipeOffset == 0 && model.rawSwipe == 0, "键盘或页码翻页会中断旧手势，恢复图标点击")
        model.swipeInProgress = true; model.swipeOffset = -50; model.rawSwipe = -50
        model.query = "Test"
        check(!model.swipeInProgress && model.swipeOffset == 0 && model.rawSwipe == 0, "开始搜索会终止旧手势状态")
        model.query = ""; model.page = 0; model.pageWidth = 1000
        check(model.beginMousePaging(timestamp: 10), "空白处鼠标拖动可开始翻页")
        model.updateMousePaging(displacement: -300, timestamp: 10.2)
        check(model.mousePaging && model.swipeInProgress && model.rawSwipe == -300, "鼠标位移持续跟踪且不触发图标拖动")
        model.endMousePaging(displacement: -300, timestamp: 10.22)
        check(model.page == 1 && !model.mousePaging && !model.swipeInProgress && !model.editing, "鼠标松手翻页且不会进入抖动模式")
        check(model.layout == baseline, "鼠标翻页不改变应用排列")
        _ = model.beginMousePaging(timestamp: 11)
        model.updateMousePaging(displacement: -10, timestamp: 11.1)
        model.endMousePaging(displacement: -10, timestamp: 11.3)
        check(model.page == 1, "鼠标轻微位移回弹")
        _ = model.beginMousePaging(timestamp: 12)
        model.updateMousePaging(displacement: 300, timestamp: 12.2)
        model.endMousePaging(displacement: 300, timestamp: 12.22)
        check(model.page == 0, "鼠标向右拖动返回上一页")
        _ = model.beginMousePaging(timestamp: 13)
        model.updateMousePaging(displacement: -50, timestamp: 13.02)
        model.endMousePaging(displacement: -50, timestamp: 13.03)
        check(model.page == 1, "鼠标短距离快速甩动可以翻页")
        _ = model.beginMousePaging(timestamp: 14)
        model.updateMousePaging(displacement: -50, timestamp: 14.02)
        model.endMousePaging(displacement: -50, timestamp: 14.5)
        check(model.page == 1, "鼠标暂停后释放不使用过期甩动速度")
        _ = model.beginMousePaging(timestamp: 15)
        model.updateMousePaging(displacement: -500, timestamp: 15.2)
        model.endMousePaging(displacement: -500, timestamp: 15.22, cancelled: true)
        check(model.page == 1 && model.swipeOffset == 0, "取消鼠标翻页会归位")
        model.navigate(to: 0)
        _ = model.beginMousePaging(timestamp: 16)
        model.updateMousePaging(displacement: 300, timestamp: 16.2)
        model.endMousePaging(displacement: 300, timestamp: 16.22)
        check(model.page == 0, "鼠标向右拖第一页不能越界")
        model.navigate(to: 2)
        _ = model.beginMousePaging(timestamp: 17)
        model.updateMousePaging(displacement: -300, timestamp: 17.2)
        model.endMousePaging(displacement: -300, timestamp: 17.22)
        check(model.page == 2, "鼠标向左拖最后一页不能越界")
        _ = model.beginMousePaging(timestamp: 18)
        model.navigate(to: 0)
        model.endMousePaging(displacement: -500, timestamp: 18.2)
        check(model.page == 0 && !model.mousePaging, "按页码后旧鼠标松手不再次翻页")
        _ = model.beginMousePaging(timestamp: 19)
        model.query = "Test"
        model.endMousePaging(displacement: -500, timestamp: 19.2)
        check(model.page == 0 && !model.mousePaging, "开始搜索取消鼠标翻页")
        model.query = ""; model.editingFolderName = true
        check(!model.beginMousePaging(timestamp: 20), "文件夹名称编辑时不抢鼠标手势")
        model.editingFolderName = false
        model.beginDrag(apps[0].id, source: NSObject())
        check(!model.beginMousePaging(timestamp: 21), "图标拖动期间不会并发鼠标翻页")
        model.finishDrag(operationSucceeded: false)
        model.apps = Array(apps.prefix(1))
        check(!model.beginMousePaging(timestamp: 22), "单页时拖动空白不会开始翻页")
        model.apps = apps
        func mouseWheel(_ vertical: Int32, horizontal: Int32 = 0, precise: Bool = false, time: Double) -> NSEvent {
            let cg = CGEvent(scrollWheelEvent2Source: nil, units: precise ? .pixel : .line, wheelCount: 2, wheel1: vertical, wheel2: horizontal, wheel3: 0)!
            cg.timestamp = UInt64(time * 1_000_000_000)
            return NSEvent(cgEvent: cg)!
        }
        let detent = mouseWheel(-1, time: 30)
        check(!detent.hasPreciseScrollingDeltas, "普通滚轮事件保持非精确单位")
        model.scroll(detent)
        check(model.page == 1, "普通滚轮一格即可翻页")
        model.scroll(mouseWheel(-2, time: 30.05))
        check(model.page == 1, "连续滚轮事件不会瞬间跳多页")
        model.scroll(mouseWheel(-1, time: 30.5))
        check(model.page == 2, "间隔后滚轮可继续翻下一页")
        model.scroll(mouseWheel(1, time: 30.51))
        check(model.page == 1, "反向滚轮立即响应")
        model.scroll(mouseWheel(-80, precise: true, time: 31))
        check(model.page == 2 && !model.swipeInProgress, "高精度垂直鼠标滚轮也可翻页，不遗留手势状态")
        model.navigate(to: 0)
        model.scroll(mouseWheel(0, horizontal: -1, time: 32))
        check(model.page == 1, "横向鼠标滚轮支持翻页")
        _ = model.beginMousePaging(timestamp: 33)
        model.scroll(mouseWheel(-1, time: 34))
        check(model.page == 1 && model.mousePaging, "鼠标拖动期间滚轮不会干扰正在进行的手势")
        model.finishSwipe(cancelled: true)
        model.layout = LaunchLayout(entries: [LaunchEntry(id: "mouse-folder", folderName: "Test", appIDs: Array(apps.prefix(45)).map(\.id))] + apps.dropFirst(45).map { .app($0.id) })
        model.openFolder("mouse-folder")
        _ = model.beginMousePaging(timestamp: 35)
        model.updateMousePaging(displacement: -300, timestamp: 35.2)
        model.endMousePaging(displacement: -300, timestamp: 35.22)
        check(model.folderPage == 1 && model.page == 1, "鼠标在文件夹中只翻文件夹页")
        _ = model.beginMousePaging(timestamp: 36)
        model.closeFolder()
        check(!model.mousePaging && model.swipeOffset == 0, "关闭文件夹会清理鼠标翻页")
        print("通过 \(checks) 项动画交互状态检查")
    }
}
